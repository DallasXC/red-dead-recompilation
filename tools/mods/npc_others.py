#!/usr/bin/env python3
"""The story levels' people, for the spawner's "Acts like" from other
levels: each level's enemy file (<level>_var_<n>.enm in lvls_sng/*.dat)
read for its people's AI table, character, side and guns; written as
src/rdr_npc_others.inc, and its animals (horses, cattle, buffalo, dogs) as
src/rdr_npc_animals.inc beside it (names only: no game data is copied).

    npc_others.py <game dir> <out.inc>
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dave  # noqa: E402

CHAPTERS = {
    ("perfnew", 1): "Chapter 1", ("hng", 1): "Chapter 2", ("sher70", 1): "Chapter 3",
    ("traincar", 1): "Chapter 4", ("traingood", 1): "Chapter 5", ("ghost", 1): "Chapter 6",
    ("shernite", 1): "Chapter 7", ("bomb", 1): "Chapter 8", ("gunsmoke", 1): "Chapter 9",
    ("cemetery", 1): "Chapter 10", ("ranch", 1): "Chapter 11", ("barfight", 1): "Chapter 12",
    ("bridge", 1): "Chapter 13", ("coach", 1): "Chapter 14", ("woods", 1): "Chapter 15",
    ("core", 1): "Chapter 16", ("corenew", 1): "Chapter 17", ("msn", 1): "Chapter 18",
    ("msncyn", 1): "Chapter 19", ("fort", 1): "Chapter 20", ("train", 1): "Chapter 21",
    ("trainend", 1): "Chapter 22", ("roydusk", 6): "Chapter 23", ("royfinal", 7): "Chapter 24",
    ("mans", 1): "Chapter 25", ("mansintb", 1): "Chapter 26", ("mansroof", 1): "Chapter 27",
}
BRIMSTONE = {"tomb": "Brimstone", "bank": "Brimstone bank", "bar": "Brimstone saloon",
             "closhop": "Brimstone clothes shop", "genstore": "Brimstone store",
             "gunshop": "Brimstone gun shop", "tombsher": "Brimstone sheriff's office",
             "jailnew": "Brimstone jail", "barnight": "Brimstone saloon (night)"}
ANIMALS = {"shr", "bfl", "bul", "hrs", "hr2", "doa", "dog", "dg1", "dg2"}
ANIMAL_NAMES = {"shr": "Horse", "hr2": "Horse", "bfl": "Buffalo", "bul": "Cow", "doa": "Dog",
                "dog": "Dog", "dg1": "Dog", "dg2": "Dog", "hrs": "Horse"}
SKIP_GROUPS = {"Doggies", "Horses", "cows", "Buffalo", "Actors", "Tutorials", "Tutors"}


def label(level, var):
    if (level, var) in CHAPTERS:
        return CHAPTERS[(level, var)]
    if level in BRIMSTONE:
        return BRIMSTONE[level]
    return None                     # levels no chapter uses


def main(game, out):
    rows, seen, beasts, seen_b = [], set(), [], set()
    for p in sorted(glob.glob(os.path.join(game, "lvls_sng", "*.dat"))):
        data, ents = dave.read(p)
        for name, do, size, packed in ents:
            m = re.match(r"lvl_(\w+)_var_(\d+)\.enm$", name)
            if not m:
                continue
            where = label(m.group(1), int(m.group(2)))
            if not where:
                continue
            text = dave.payload(data, do, size, packed).decode("latin-1")
            for blk in re.findall(r"Enemy\s*\{(.*?)\n\}", text, re.S):
                def f(k):
                    mm = re.search(r"\n\s*" + k + r"\s+([^\r\n]*)", "\n" + blk)
                    return mm.group(1).strip() if mm else ""
                table, ty, group = f("Table"), f("Type").lower(), f("Group")
                if table and ty in ANIMALS:
                    # (the train's and rail-shooter's horses carry riders
                    # on a script: left out)
                    if any(w in table.lower() for w in ("railshooter", "player", "wartrain_horse", "trainboss")):
                        continue
                    if (ty, table.lower()[:8]) not in seen_b and ty not in {b[2] for b in beasts if b[0] == where}:
                        seen_b.add((ty, table.lower()[:8]))
                        beasts.append((where, table, ty))
                    continue
                # (a cannon's gunner works his chapter's cannon and nothing else)
                if any(w in table.lower() for w in ("cannon", "gatling", "gatguy")):
                    continue
                if (not table or not ty or ty in ANIMALS or group in SKIP_GROUPS
                        or table.upper() == "ACTOR" or "test" in table.lower() or "test" in group.lower()):
                    continue
                try:
                    team = int(f("Alignment").split()[0])
                except (ValueError, IndexError):
                    team = 0
                armed = "1" in f("WeaponList").split()
                # one of each kind of person a level has (its many "group a
                # 1, 2, ..." tables mostly differ in where they go)
                key = (where, ty, team, armed)
                if table.lower() in seen or key in seen:
                    continue
                seen.add(table.lower())
                seen.add(key)
                rows.append((where, table, ty, team, armed))
    with open(out, "w", newline="\n") as o:
        o.write("/* Generated by tools/mods/npc_others.py: the story levels' people (AI table,\n"
                " * character, side, guns), for the spawner's \"Acts like\" from other levels. */\n")
        for where, table, ty, team, armed in rows:
            o.write('{ "%s", "%s", "%s", %d, %d },\n' % (where, table, ty, team, int(armed)))
    print(f"{len(rows)} people written to {out}")
    out_b = os.path.join(os.path.dirname(out), "rdr_npc_animals.inc")
    with open(out_b, "w", newline="\n") as o:
        o.write("/* Generated by tools/mods/npc_others.py: the story levels' animals (where,\n"
                " * AI table, character, name, made as an animal: dogs are people to the game). */\n")
        for where, table, ty in beasts:
            o.write('{ "%s", "%s", "%s", "%s", %d },\n' % (where, table, ty, ANIMAL_NAMES.get(ty, ty),
                                                         0 if ANIMAL_NAMES.get(ty) == "Dog" else 1))
    print(f"{len(beasts)} animals written to {out_b}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
